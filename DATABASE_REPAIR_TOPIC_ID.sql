-- Ghostea deployment repair: legacy moderation log topic column
-- Run this FIRST if Supabase reports:
--   ERROR 42703: column "topic_id" does not exist
--
-- This is safe for an existing Ghostea database. It only adds the missing
-- nullable column and the two topic-aware indexes.

begin;

create table if not exists public.ghostea_moderation_logs (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    user_id bigint,
    topic_id bigint,
    action text not null,
    reason text,
    details text,
    created_at timestamptz not null default now()
);

alter table public.ghostea_moderation_logs
    add column if not exists topic_id bigint;

create index if not exists idx_ghostea_moderation_logs_chat
    on public.ghostea_moderation_logs(chat_id, created_at desc);

create index if not exists idx_ghostea_moderation_logs_chat_topic_time
    on public.ghostea_moderation_logs(chat_id, topic_id, created_at desc);

create index if not exists idx_ghostea_moderation_logs_chat_topic_user_time
    on public.ghostea_moderation_logs(chat_id, topic_id, user_id, created_at desc);

commit;
